import assert from 'node:assert/strict';
import {normalizeTodo,todoFingerprint,googleEventFromTodo,eventFingerprint,planCalendarSync,
 notesWithoutCrmCustomerFooter} from '../calendar-sync-core.mjs';
const todo={id:123,text:'客戶拜訪',date:'2026-10-27',time:'09:30',notes:'會議',customerName:'測試客戶',done:false};
const event={id:'g-1',summary:'客戶拜訪',description:'會議',start:{dateTime:'2026-10-27T09:30:00+08:00'},end:{dateTime:'2026-10-27T10:30:00+08:00'}};
const links={'123':{eventId:'g-1',localFingerprint:todoFingerprint(todo),remoteFingerprint:eventFingerprint(event)}};
assert.equal(googleEventFromTodo(todo).start.timeZone,'Asia/Taipei');
assert.equal(googleEventFromTodo(todo).extendedProperties.private.honbinCrmTodoId,'123');
assert.equal(googleEventFromTodo({...todo,time:''}).end.date,'2026-10-28');
assert.equal(planCalendarSync({todos:[todo],events:[event],links}).operations.length,0);
let p=planCalendarSync({todos:[{...todo,notes:'CRM 新內容'}],events:[event],links});
assert.deepEqual(p.operations.map(x=>x.type),['UPDATE_GOOGLE']);
p=planCalendarSync({todos:[todo],events:[{...event,summary:'手機修改'}],links});
assert.deepEqual(p.operations.map(x=>x.type),['UPDATE_CRM']);
p=planCalendarSync({todos:[{...todo,notes:'CRM 新內容'}],events:[{...event,summary:'手機修改'}],links});
assert.deepEqual(p.conflicts.map(x=>x.reason),['BOTH_CHANGED']);
assert.equal(p.operations.length,0,'conflicts never auto-overwrite');
p=planCalendarSync({todos:[],events:[event],links});
assert.deepEqual(p.conflicts.map(x=>x.reason),['CRM_RECORD_MISSING']);
assert.equal(p.operations.length,0,'no automatic CRM deletion');
p=planCalendarSync({todos:[todo],events:[],links});
assert.deepEqual(p.conflicts.map(x=>x.reason),['GOOGLE_EVENT_MISSING_OR_CANCELLED']);
assert.equal(p.operations.length,0,'no automatic Google deletion');
p=planCalendarSync({todos:[todo],events:[],links:{}});
assert.deepEqual(p.operations.map(x=>x.type),['CREATE_GOOGLE']);
p=planCalendarSync({todos:[],events:[event],links:{}});
assert.deepEqual(p.operations.map(x=>x.type),['IMPORT_TO_CRM']);
p=planCalendarSync({todos:[todo],events:[{...event,extendedProperties:{private:{honbinCrmTodoId:'123'}}}],links:{}});
assert.deepEqual(p.conflicts.map(x=>x.reason),['UNLINKED_EXISTING_CRM_EVENT']);
assert.equal(p.operations.filter(x=>x.type==='IMPORT_TO_CRM').length,0,'lost mapping never duplicates CRM task');
assert.equal(p.operations.filter(x=>x.type==='CREATE_GOOGLE').length,0,'lost mapping must not create a second Google event');
p=planCalendarSync({todos:[todo],events:[{...event,extendedProperties:{private:{honbinCrmTodoId:'123'}}}],links:{}});
assert.deepEqual(p.operations,[],'unlinked existing Google tag must block both directions');
assert.deepEqual(p.conflicts.map(x=>x.reason),['UNLINKED_EXISTING_CRM_EVENT']);
p=planCalendarSync({todos:[],events:[{...event,extendedProperties:{private:{honbinCrmTodoId:'deleted-id'}}}],links:{}});
assert.deepEqual(p.operations,[],'deleted CRM todo must not resurrect from Google');
assert.deepEqual(p.conflicts.map(x=>x.reason),['ORPHANED_CRM_EVENT']);
p=planCalendarSync({todos:[todo],events:[
 {...event,extendedProperties:{private:{honbinCrmTodoId:'123'}}},
 {...event,id:'g-duplicate',extendedProperties:{private:{honbinCrmTodoId:'123'}}}
],links:{}});
assert.equal(p.operations.length,0,'two remote tags must never trigger another creation');
assert.deepEqual(p.conflicts.map(x=>x.reason),['MULTIPLE_GOOGLE_EVENTS_FOR_TODO']);
p=planCalendarSync({todos:[todo],events:[{...event,extendedProperties:{private:{honbinCrmTodoId:'someone-else'}}}],links});
assert.equal(p.operations.length,0,'wrong event owner cannot receive CRM update');
assert.deepEqual(p.conflicts.map(x=>x.reason),['GOOGLE_EVENT_OWNER_MISMATCH']);
p=planCalendarSync({todos:[todo,{...todo,id:456}],events:[event],links:{
 '123':links['123'],'456':{...links['123']}
}});
assert.equal(p.operations.length,0,'two CRM records cannot update the same event');
assert.deepEqual(p.conflicts.map(x=>x.reason),['DUPLICATE_EVENT_LINK','DUPLICATE_EVENT_LINK']);
p=planCalendarSync({todos:[todo,{...todo,text:'另一筆但錯誤重複 ID'}],events:[],links:{}});
assert.equal(p.operations.length,0,'duplicated local IDs must stop all batch writes');
assert.deepEqual(p.conflicts.map(x=>x.reason),['DUPLICATE_LOCAL_TODO_ID']);
p=planCalendarSync({todos:[{...todo,date:''}],events:[],links:{}});
assert.equal(p.operations.length,0);
assert.deepEqual(p.skipped.map(x=>x.reason),['NO_VALID_DATE']);
assert.equal(normalizeTodo({id:1,date:'2026-10-27'}).time,'');
assert.equal(normalizeTodo({...todo,date:'2026-02-30'}),null,'impossible dates must not sync');
assert.equal(normalizeTodo({...todo,time:'25:61'}),null,'invalid time must not silently become all-day');
assert.equal(planCalendarSync({todos:[{...todo,date:'2026-02-30'}],events:[]}).operations.length,0);
assert.equal(notesWithoutCrmCustomerFooter('會議\n客戶：測試客戶','測試客戶'),'會議');
assert.equal(notesWithoutCrmCustomerFooter('客戶：測試客戶','測試客戶'),'');
assert.equal(notesWithoutCrmCustomerFooter('會議\n客戶：測試客戶\n客戶：測試客戶','測試客戶'),'會議\n客戶：測試客戶');
assert.equal(notesWithoutCrmCustomerFooter('外部改寫內容','測試客戶'),'外部改寫內容');
assert.equal(notesWithoutCrmCustomerFooter('使用者手動記錄\n客戶：乙公司','測試客戶'),'使用者手動記錄\n客戶：乙公司');
assert.equal(googleEventFromTodo({...todo,time:''}).start.date,'2026-10-27');
assert.equal(googleEventFromTodo({...todo,time:''}).end.date,'2026-10-28');
assert.equal(googleEventFromTodo({...todo,date:'2026-12-31',time:''}).end.date,'2027-01-01');
